// Writes the service worker for /kids-playground/ with the list of every file to keep offline.
//   node tools/playground/build.mjs
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../../static/kids-playground');
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    if (name.startsWith('.') || name === 'dev' || name === 'sw.js') continue;
    if (statSync(path).isDirectory()) walk(path); else files.push(relative(root, path));
  }
})(root);

const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(root, f)));
const version = hash.digest('hex').slice(0, 12);

writeFileSync(join(root, 'sw.js'), `// Generated by tools/playground/build.mjs — do not edit by hand.
// Caches the whole app so it opens offline; a new version replaces the cache on the next launch.
const CACHE = 'kids-playground-${version}';
const FILES = ${JSON.stringify(['./', ...files], null, 1)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('kids-playground-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  event.respondWith(
    caches.match(request, { ignoreSearch: true }).then((hit) => hit || fetch(request)),
  );
});
`);
console.log(`sw.js: ${files.length} files, version ${version}`);
